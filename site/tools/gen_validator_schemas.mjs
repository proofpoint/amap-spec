// Regenerate assets/validator-schemas.js from the amap-spec checkout.
// Embeds every schema verbatim (as parsed JSON) plus a few fixtures as
// examples (as their exact file text), so the validator page needs no fetch()
// and works from file://.
//
//     node tools/gen_validator_schemas.mjs [path-to-amap-spec]
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, "..");
const spec = resolve(process.argv[2] || join(site, ".."));

const schemas = {};
for (const f of readdirSync(join(spec, "schemas")).filter((f) => f.endsWith(".schema.json")).sort()) {
  schemas[f] = JSON.parse(readFileSync(join(spec, "schemas", f), "utf8"));
}

const EXAMPLES = [
  ["valid", "request-minimal.json"],
  ["valid", "notice-minimal.json"],
  ["invalid", "request-subject-trailing-newline.json"],
  ["invalid", "result-attachments-gap-index.json"],
  ["valid", "roster-basic.json"],
];
const examples = EXAMPLES.map(([dir, name]) => ({
  name,
  valid: dir === "valid",
  text: readFileSync(join(spec, "fixtures", dir, name), "utf8"),
}));

const out =
  "// GENERATED by tools/gen_validator_schemas.mjs from the amap-spec schemas and fixtures. Do not edit.\n" +
  "(function (root) {\n" +
  "  root.AMAP_SCHEMAS = " + JSON.stringify(schemas) + ";\n" +
  "  root.AMAP_EXAMPLES = " + JSON.stringify(examples) + ";\n" +
  "})(typeof window !== \"undefined\" ? window : globalThis);\n";
writeFileSync(join(site, "assets", "validator-schemas.js"), out);
console.log(`wrote assets/validator-schemas.js: ${Object.keys(schemas).length} schemas, ${examples.length} examples`);
